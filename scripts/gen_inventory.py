#!/usr/bin/env python3
"""Generate an Ansible inventory from Terraform outputs.

Step 2 of the pipeline:  Terraform outputs (IPs, bucket)  ->  ansible/inventory/hosts.ini

Usage:
    gen_inventory.py                       # runs `terraform output -json` in ./terraform
    gen_inventory.py --from-json out.json  # read a saved output (use "-" for stdin) - handy for tests

Only the Python standard library is used, so it works on any machine with python3.
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

REQUIRED_OUTPUTS = (
    "web_public_ip",
    "web_private_ip",
    "db_public_ip",
    "db_private_ip",
    "s3_bucket_name",
    "aws_region",
)


class InventoryError(Exception):
    """Raised when the Terraform outputs are missing or invalid."""


def read_terraform_outputs(tf_dir: Path) -> dict:
    """Run `terraform output -json` and return the parsed JSON."""
    try:
        result = subprocess.run(
            ["terraform", f"-chdir={tf_dir}", "output", "-json"],
            check=True,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError as exc:
        raise InventoryError("terraform is not installed or not in PATH") from exc
    except subprocess.CalledProcessError as exc:
        raise InventoryError(f"terraform output failed:\n{exc.stderr.strip()}") from exc
    return json.loads(result.stdout)


def flatten(raw: dict) -> dict:
    """{"name": {"value": X, ...}}  ->  {"name": X}"""
    return {name: item["value"] for name, item in raw.items() if "value" in item}


def validate(outputs: dict) -> None:
    missing = [key for key in REQUIRED_OUTPUTS if not outputs.get(key)]
    if missing:
        raise InventoryError(
            "missing Terraform outputs: " + ", ".join(missing) + " (did `terraform apply` finish?)"
        )
    for key in ("web_public_ip", "web_private_ip", "db_public_ip", "db_private_ip"):
        try:
            ipaddress.IPv4Address(outputs[key])
        except ValueError as exc:
            raise InventoryError(f"output {key!r} is not a valid IPv4 address: {outputs[key]!r}") from exc


def render_inventory(outputs: dict, ssh_key: Path, known_hosts: Path, ssh_user: str) -> str:
    """Return the inventory file content (deterministic -> re-runs give identical files)."""
    for path in (ssh_key, known_hosts):
        if " " in str(path):
            raise InventoryError(f"path must not contain spaces: {path}")

    ssh_args = f"-o StrictHostKeyChecking=accept-new -o UserKnownHostsFile={known_hosts}"
    lines = [
        "# GENERATED by scripts/gen_inventory.py from `terraform output -json`.",
        "# Do not edit and do not commit (it is in .gitignore).",
        "",
        "[web]",
        f"web-server ansible_host={outputs['web_public_ip']} private_ip={outputs['web_private_ip']}",
        "",
        "[db]",
        f"db-server ansible_host={outputs['db_public_ip']} private_ip={outputs['db_private_ip']}",
        "",
        "[all:vars]",
        f"ansible_user={ssh_user}",
        f"ansible_ssh_private_key_file={ssh_key}",
        "ansible_python_interpreter=/usr/bin/python3",
        f"ansible_ssh_common_args='{ssh_args}'",
        f"s3_bucket={outputs['s3_bucket_name']}",
        f"aws_region={outputs['aws_region']}",
        "",
    ]
    return "\n".join(lines)


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate an Ansible inventory from Terraform outputs.")
    parser.add_argument("--tf-dir", type=Path, default=ROOT / "terraform", help="Terraform directory")
    parser.add_argument("--from-json", metavar="FILE", help="read outputs from a JSON file ('-' = stdin)")
    parser.add_argument("--output", type=Path, default=ROOT / "ansible" / "inventory" / "hosts.ini")
    parser.add_argument("--ssh-key", type=Path, default=ROOT / ".state" / "id_ed25519")
    parser.add_argument("--known-hosts", type=Path, default=ROOT / ".state" / "known_hosts")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    try:
        if args.from_json:
            text = sys.stdin.read() if args.from_json == "-" else Path(args.from_json).read_text()
            raw = json.loads(text)
        else:
            raw = read_terraform_outputs(args.tf_dir)

        outputs = flatten(raw)
        validate(outputs)
        content = render_inventory(
            outputs,
            ssh_key=args.ssh_key.resolve(),
            known_hosts=args.known_hosts.resolve(),
            ssh_user=outputs.get("ssh_user", "ubuntu"),
        )
    except (InventoryError, json.JSONDecodeError, OSError) as exc:
        print(f"[gen_inventory] ERROR: {exc}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    print(f"[gen_inventory] wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
